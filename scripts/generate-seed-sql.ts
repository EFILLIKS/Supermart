// Writes supabase/seed.sql from the same catalogue the demo uses. Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { CATEGORIES, COUPONS, PRODUCTS } from "../src/data/catalog.ts";

const q = (v: string | number | null | undefined) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);
const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts. Catalogue and coupons only; no people or orders.", "begin;"];

CATEGORIES.forEach((c, i) => out.push(`insert into public.categories (slug, name, description, image_url, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.image)}, ${i}) on conflict (slug) do nothing;`));

for (const p of PRODUCTS) {
  const cat = CATEGORIES.find((c) => c.id === p.categoryId)!;
  const tags = `array[${p.tags.map(q).join(", ")}]::text[]`;
  out.push(`insert into public.products (category_id, slug, barcode, name, brand, description, unit, price, mrp, tax_rate, image_url, origin, tags) select id, ${[p.slug, p.barcode, p.name, p.brand, p.description, p.unit].map(q).join(", ")}, ${p.price}, ${p.mrp}, ${p.taxRate}, ${q(p.image)}, ${q(p.origin)}, ${tags} from public.categories where slug = ${q(cat.slug)} on conflict (slug) do nothing;`);
  out.push(`insert into public.inventory (product_id, quantity, reorder_level) select id, ${p.stock}, ${p.reorderLevel} from public.products where slug = ${q(p.slug)} on conflict (product_id) do nothing;`);
}

for (const c of COUPONS) {
  out.push(`insert into public.coupons (code, description, kind, value, min_order, max_discount, usage_limit, used_count, is_active) values (${q(c.code)}, ${q(c.description)}, ${q(c.kind)}, ${c.value}, ${c.minOrder}, ${q(c.maxDiscount)}, ${q(c.usageLimit)}, ${c.usedCount}, ${c.active}) on conflict (code) do nothing;`);
}

out.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote ${CATEGORIES.length} categories, ${PRODUCTS.length} products, ${COUPONS.length} coupons.`);
